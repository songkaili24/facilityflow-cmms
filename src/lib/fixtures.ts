/* Timestamps are generated relative to module load so the demo data always
   reads as "live" — an overdue SLA is overdue today, not in 2024. */
const NOW = new Date();

function hoursAgo(h: number): string {
  return new Date(NOW.getTime() - h * 3_600_000).toISOString();
}
function hoursFromNow(h: number): string {
  return new Date(NOW.getTime() + h * 3_600_000).toISOString();
}
function daysFromNow(d: number, hour = 9, minute = 0): string {
  return new Date(NOW.getFullYear(), NOW.getMonth(), NOW.getDate() + d, hour, minute).toISOString();
}
function daysAgo(d: number, hour = 9): string {
  return daysFromNow(-d, hour);
}

let tSeq = 0;
function tl(p: Omit<TimelineEntry, "id">): TimelineEntry {
  return { id: `t-${tSeq++}`, ...p };
}

