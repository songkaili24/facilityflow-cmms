function parts(p: Array<[string, number, number, "on_hand" | "ordered" | "backordered"]>) {
  return p.map(([name, qty, unitCost, status], i) => ({
    id: `part-${partSeq()}-${i}`,
    name,
    qty,
    unitCost,
    status,
  }));
}
let pSeq = 0;
function partSeq() {
  return ++pSeq;
}

